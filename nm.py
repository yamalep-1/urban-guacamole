selected_country = None  # Глобальная переменная для хранения выбранной страны

def on_country_select(event):
    """Обновляет список блюд при выборе страны."""
    global selected_country
    
    selection = country_list.curselection()
    if not selection:
        return
    
    selected_country = country_list.get(selection[0])  # Сохраняем страну
    
    # Очищаем список блюд
    dish_list.delete(0, tk.END)
    
    # Заполняем блюдами
    for dish in food_data[selected_country]:
        dish_list.insert(tk.END, f"  [+] {dish['name']}")
        
    # Очищаем правую панель
    info_text.config(state="normal")
    info_text.delete(1.0, tk.END)
    info_text.insert(tk.END, f">> СТРАНА: {selected_country}\n\n", "title")
    info_text.insert(tk.END, "═" * 50 + "\n\n", "divider")
    info_text.insert(tk.END, ">> ВЫБЕРИТЕ БЛЮДО ДЛЯ ПРОСМОТРА\n", "welcome")
    info_text.insert(tk.END, ">> ОЖИДАНИЕ ВВОДА...\n\n", "glitch")
    info_text.insert(tk.END, "═" * 50 + "\n", "divider")
    info_text.config(state="disabled")

def on_dish_select(event):
    """Отображает подробную информацию о блюде."""
    dish_sel = dish_list.curselection()
    
    # Используем сохранённую страну вместо curselection()
    if not selected_country or not dish_sel:
        return
        
    dish_index = dish_sel[0]
    dish = food_data[selected_country][dish_index]
    
    info_text.config(state="normal")
    info_text.delete(1.0, tk.END)
    
    # Формируем киберпанк текст
    info_text.insert(tk.END, f"╔══════════════════════════════════════════╗\n", "divider")
    info_text.insert(tk.END, f"║  {dish['name'].upper():^42}║\n", "title")
    info_text.insert(tk.END, f"══════════════════════════════════════════╝\n\n", "divider")
    
    info_text.insert(tk.END, ">> ХАРАКТЕРИСТИКА:\n", "header")
    info_text.insert(tk.END, f"{dish['characteristic']}\n\n", "body")
    
    info_text.insert(tk.END, ">> ИНГРЕДИЕНТЫ:\n", "header")
    info_text.insert(tk.END, f"{dish['ingredients']}\n\n", "body")
    
    info_text.insert(tk.END, ">> РЕЦЕПТ:\n", "header")
    info_text.insert(tk.END, f"{dish['recipe']}\n", "body")
    
    info_text.insert(tk.END, "\n" + "═" * 50 + "\n", "divider")
    info_text.insert(tk.END, "[КОНЕЦ ДАННЫХ]\n", "glitch")
    
    info_text.config(state="disabled")

# Привязка событий
country_list.bind("<<ListboxSelect>>", on_country_select)
dish_list.bind("<<ListboxSelect>>", on_dish_select)

